def _planner_draft(c):
    name = c.get("project_name", "本项目")
    tasks = [
        ("T1", "搭建项目骨架与内容仓", "high", 4, []),
        ("T2", "需求池与一句话需求录入", "high", 3, ["T1"]),
        ("T3", "PRD 起草流水线（PM-Agent 子图）", "high", 8, ["T2"]),
        ("T4", "阶段门与审批挂起机制", "high", 6, ["T3"]),
        ("T5", "打断-注入-恢复链路", "high", 6, ["T4"]),
        ("T6", "任务看板投影与过滤", "medium", 5, ["T4"]),
        ("T7", "导入解析模块", "medium", 6, ["T1"]),
        ("T8", "数据校验与清洗", "medium", 5, ["T7"]),
        ("T9", "报告模板引擎", "medium", 6, ["T8"]),
        ("T10", "周报导出（Markdown/CSV）", "low", 4, ["T9"]),
        ("T11", "审计事件流查询与导出", "low", 4, ["T6"]),
        ("T12", "端到端冒烟与文档", "low", 5, ["T10", "T11"]),
    ]
    lines = [f"# WBS：{name}", "", "## 任务分解", ""]
    wbs = []
    for tid, title, pri, est, deps in tasks:
        dep_str = f"（依赖 {', '.join(deps)}）" if deps else ""
        lines.append(f"- **{tid}** {title} · 优先级 {pri} · {est}h {dep_str}")
        wbs.append(
            {"id": tid, "title": f"{tid} {title}", "priority": pri,
             "estimate_hours": est, "depends_on": deps}
        )
    import json

    lines += [
        "",
        f"## 补充约束\n{_constraints_block(c)}",
        "",
        "## 工作项清单（系统据此创建）",
        "",
        "```wbs",
        json.dumps(wbs, ensure_ascii=False, indent=2),
        "```",
    ]
    return "\n".join(lines)


