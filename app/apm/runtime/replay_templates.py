"""Replay fixtures: deterministic response templates keyed by (role, node).

Templates embed run context so injected constraints change outputs — this is
what makes "interrupt → inject → resume → artifact contains constraint"
verifiable in CI without a real model. Recordings from `record` mode override
templates (same key space).
"""
from __future__ import annotations

from typing import Any

from apm import config


def _constraints_block(context: dict[str, Any]) -> str:
    constraints = context.get("constraints") or []
    if not constraints:
        return "（无）"
    return "\n".join(f"- {c}" for c in constraints)


def _recorded(key: str) -> str | None:
    path = config.settings.fixtures_dir / "recordings.yaml"
    if not path.exists():
        return None
    import yaml

    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    return data.get(key)


def render(role: str, node: str, context: dict[str, Any]) -> str:
    key = f"{role}/{node}"
    recorded = _recorded(key)
    if recorded is not None:
        return recorded
    fn = _TEMPLATES.get(key)
    if fn is None:
        raise KeyError(f"no replay fixture for '{key}'")
    return fn(context)


